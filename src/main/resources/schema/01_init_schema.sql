-- =============================================================================
-- SQL KATA · Единая схема и тестовые данные
-- PostgreSQL 16+
--
-- Домен: интернет-магазин + финтех-биллинг.
-- Данные намеренно содержат NULL, «сирот», возвраты, неоплаченные заказы,
-- дубликаты событий и иерархию категорий — это нужно для будущих уровней.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. Справочники и организационная структура
-- -----------------------------------------------------------------------------
CREATE TABLE departments (
    department_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            text        NOT NULL UNIQUE,
    city            text        NOT NULL,
    annual_budget   numeric(12, 2) NOT NULL CHECK (annual_budget >= 0),
    created_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE employees (
    employee_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name       text        NOT NULL,
    email           text        NOT NULL UNIQUE,
    department_id   integer     REFERENCES departments (department_id) ON DELETE SET NULL,
    manager_id      integer     REFERENCES employees (employee_id) ON DELETE SET NULL,
    job_title       text        NOT NULL,
    salary          numeric(10, 2) NOT NULL CHECK (salary > 0),
    hired_at        date        NOT NULL,
    is_remote       boolean     NOT NULL DEFAULT false,
    skills          text[]      NOT NULL DEFAULT '{}',
    CONSTRAINT employees_not_own_manager CHECK (manager_id IS DISTINCT FROM employee_id)
);

CREATE INDEX employees_department_idx ON employees (department_id);
CREATE INDEX employees_manager_idx ON employees (manager_id);

-- -----------------------------------------------------------------------------
-- 2. Пользователи, каталог
-- -----------------------------------------------------------------------------
CREATE TABLE users (
    user_id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name       text        NOT NULL,
    email           text        NOT NULL UNIQUE,
    phone           text,
    country         char(2)     NOT NULL CHECK (char_length(country) = 2),
    status          text        NOT NULL CHECK (status IN ('active', 'inactive', 'blocked')),
    loyalty_tier    text        CHECK (loyalty_tier IN ('bronze', 'silver', 'gold', 'platinum')),
    registered_at   timestamptz NOT NULL,
    date_of_birth   date,
    preferences     jsonb       NOT NULL DEFAULT '{}'::jsonb,
    marketing_opt_in boolean    NOT NULL DEFAULT false,
    tags            text[]      NOT NULL DEFAULT '{}',
    CONSTRAINT users_preferences_is_object CHECK (jsonb_typeof(preferences) = 'object')
);

CREATE INDEX users_status_idx ON users (status);
CREATE INDEX users_country_status_idx ON users (country, status);
CREATE INDEX users_preferences_gin_idx ON users USING gin (preferences);
CREATE INDEX users_tags_gin_idx ON users USING gin (tags);

CREATE TABLE categories (
    category_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            text        NOT NULL UNIQUE,
    slug            text        NOT NULL UNIQUE,
    parent_id       integer     REFERENCES categories (category_id) ON DELETE RESTRICT,
    is_active       boolean     NOT NULL DEFAULT true,
    CONSTRAINT categories_not_own_parent CHECK (parent_id IS DISTINCT FROM category_id)
);

CREATE INDEX categories_parent_idx ON categories (parent_id);

CREATE TABLE products (
    product_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku             text        NOT NULL UNIQUE,
    name            text        NOT NULL,
    category_id     integer     REFERENCES categories (category_id) ON DELETE SET NULL,
    price           numeric(10, 2) NOT NULL CHECK (price > 0),
    cost            numeric(10, 2) NOT NULL CHECK (cost >= 0),
    stock           integer     CHECK (stock >= 0),
    rating          numeric(2, 1) CHECK (rating BETWEEN 0 AND 5),
    tags            text[]      NOT NULL DEFAULT '{}',
    attributes      jsonb       NOT NULL DEFAULT '{}'::jsonb,
    is_active       boolean     NOT NULL DEFAULT true,
    created_at      date        NOT NULL,
    CONSTRAINT products_attributes_is_object CHECK (jsonb_typeof(attributes) = 'object')
);

CREATE INDEX products_category_idx ON products (category_id);
CREATE INDEX products_active_price_idx ON products (is_active, price);
CREATE INDEX products_tags_gin_idx ON products USING gin (tags);
CREATE INDEX products_attributes_gin_idx ON products USING gin (attributes);

-- -----------------------------------------------------------------------------
-- 3. Заказы, позиции заказа, платежи
-- -----------------------------------------------------------------------------
CREATE TABLE orders (
    order_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         integer     NOT NULL REFERENCES users (user_id) ON DELETE RESTRICT,
    status          text        NOT NULL CHECK (status IN ('pending', 'paid', 'shipped', 'delivered', 'cancelled', 'returned')),
    total_amount    numeric(12, 2) NOT NULL CHECK (total_amount > 0),
    currency        char(3)     NOT NULL DEFAULT 'RUB',
    created_at      timestamptz NOT NULL,
    shipped_at      timestamptz,
    promo_code      text,
    delivery_address jsonb,
    CONSTRAINT orders_shipped_after_created CHECK (shipped_at IS NULL OR shipped_at >= created_at)
);

CREATE INDEX orders_user_idx ON orders (user_id);
CREATE INDEX orders_created_at_idx ON orders (created_at);
CREATE INDEX orders_status_created_idx ON orders (status, created_at);

CREATE TABLE order_items (
    order_item_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        integer     NOT NULL REFERENCES orders (order_id) ON DELETE CASCADE,
    product_id      integer     NOT NULL REFERENCES products (product_id) ON DELETE RESTRICT,
    quantity        integer     NOT NULL CHECK (quantity > 0),
    unit_price      numeric(10, 2) NOT NULL CHECK (unit_price > 0),
    discount_percent numeric(5, 2) NOT NULL DEFAULT 0 CHECK (discount_percent BETWEEN 0 AND 100),
    line_total      numeric(12, 2) GENERATED ALWAYS AS (
        round(quantity * unit_price * (1 - discount_percent / 100.0), 2)
    ) STORED,
    CONSTRAINT order_items_unique_product UNIQUE (order_id, product_id)
);

CREATE INDEX order_items_order_idx ON order_items (order_id);
CREATE INDEX order_items_product_idx ON order_items (product_id);

CREATE TABLE payments (
    payment_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        integer     NOT NULL REFERENCES orders (order_id) ON DELETE RESTRICT,
    amount          numeric(12, 2) NOT NULL CHECK (amount <> 0),
    currency        char(3)     NOT NULL DEFAULT 'RUB',
    method          text        NOT NULL CHECK (method IN ('card', 'sbp', 'wallet', 'invoice')),
    status          text        NOT NULL CHECK (status IN ('authorized', 'captured', 'failed', 'refunded')),
    paid_at         timestamptz NOT NULL,
    transaction_ref text        NOT NULL UNIQUE,
    metadata        jsonb       NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT payments_sign_matches_status CHECK (
        (status = 'refunded' AND amount < 0)
        OR (status <> 'refunded' AND amount > 0)
    ),
    CONSTRAINT payments_metadata_is_object CHECK (jsonb_typeof(metadata) = 'object')
);

CREATE INDEX payments_order_idx ON payments (order_id);
CREATE INDEX payments_status_idx ON payments (status);
CREATE INDEX payments_paid_at_idx ON payments (paid_at);

-- -----------------------------------------------------------------------------
-- 4. Сессии и аудит
-- -----------------------------------------------------------------------------
CREATE TABLE user_sessions (
    session_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         integer     REFERENCES users (user_id) ON DELETE SET NULL,
    started_at      timestamptz NOT NULL,
    ended_at        timestamptz,
    device_type     text        NOT NULL CHECK (device_type IN ('desktop', 'mobile', 'tablet')),
    ip              inet,
    conversion_order_id integer REFERENCES orders (order_id) ON DELETE SET NULL,
    CONSTRAINT sessions_ended_after_started CHECK (ended_at IS NULL OR ended_at >= started_at)
);

CREATE INDEX sessions_user_started_idx ON user_sessions (user_id, started_at);
CREATE INDEX sessions_device_idx ON user_sessions (device_type);
CREATE INDEX sessions_conversions_idx ON user_sessions (conversion_order_id)
    WHERE conversion_order_id IS NOT NULL;

CREATE TABLE audit_logs (
    log_id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id   integer     REFERENCES users (user_id) ON DELETE SET NULL,
    entity_type     text        NOT NULL,
    entity_id       bigint,
    action          text        NOT NULL,
    occurred_at     timestamptz NOT NULL,
    success         boolean     NOT NULL,
    payload         jsonb       NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT audit_payload_is_object CHECK (jsonb_typeof(payload) = 'object')
);

CREATE INDEX audit_actor_idx ON audit_logs (actor_user_id, occurred_at);
CREATE INDEX audit_entity_idx ON audit_logs (entity_type, entity_id);
CREATE INDEX audit_occurred_at_idx ON audit_logs (occurred_at);
CREATE INDEX audit_payload_gin_idx ON audit_logs USING gin (payload);

