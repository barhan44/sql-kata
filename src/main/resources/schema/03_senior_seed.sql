-- 5. Граф зависимостей задач: DAG и отдельный цикл 13 → 14 → 15 → 13
--    Ребро task_id → depends_on_task_id означает «зависит от».
-- -----------------------------------------------------------------------------
CREATE TABLE task_nodes (
    task_id   integer PRIMARY KEY,
    task_name text NOT NULL UNIQUE
);

CREATE TABLE task_dependencies (
    task_id            integer NOT NULL REFERENCES task_nodes (task_id) ON DELETE CASCADE,
    depends_on_task_id integer NOT NULL REFERENCES task_nodes (task_id) ON DELETE CASCADE,
    PRIMARY KEY (task_id, depends_on_task_id),
    CHECK (task_id <> depends_on_task_id)
);

CREATE INDEX task_dependencies_dep_idx
    ON task_dependencies (depends_on_task_id);

