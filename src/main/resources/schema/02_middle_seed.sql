-- Кандидаты контакта из разных источников. В одной таблице намеренно
-- несколько записей на пользователя с разными статусами достоверности.
CREATE TABLE user_contact_candidates (
    contact_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     integer NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    source      text    NOT NULL CHECK (source IN ('crm', 'website', 'support', 'import')),
    status      text    NOT NULL CHECK (status IN ('verified', 'pending', 'stale', 'invalid')),
    email       text,
    phone       text,
    updated_at  timestamptz NOT NULL,
    CONSTRAINT user_contact_has_value CHECK (email IS NOT NULL OR phone IS NOT NULL)
);

CREATE INDEX user_contact_candidates_user_idx
    ON user_contact_candidates (user_id, updated_at DESC);

