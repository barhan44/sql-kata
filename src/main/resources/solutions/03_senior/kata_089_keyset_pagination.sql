-- KATA 089 · Эталонное решение
-- =============================================================================
-- Почему так:
--   • Row-value comparison (created_at, order_id) < (cursor_time, cursor_id)
--     корректно реализует составной порядок: сначала сравнивается время,
--     затем id при равенстве времени.
--   • Простое `created_at < cursor_time` потеряло бы заказы с тем же
--     created_at, но меньшим order_id. OR-условие сработало бы, но row-value
--     читается короче и позволяет планировщику использовать составной индекс
--     (created_at DESC, order_id DESC).
--   • OFFSET O(N) читает и отбрасывает все предыдущие строки; на глубоких
--     страницах это линейно растёт. Keyset ищет точку по индексу и читает
--     только LIMIT строк, поэтому стоимость страницы примерно постоянна.
--   • Курсор нельзя «прыгнуть» на произвольную страницу без знания ключа
--     последней строки — это осознанный trade-off ради стабильной скорости.
--   • Составной индекс orders(created_at DESC, order_id DESC) создан в
--     senior seed именно для этого сценария.
-- =============================================================================

SELECT
    order_id,
    user_id,
    created_at,
    total_amount
FROM orders
WHERE (created_at, order_id) < (
    TIMESTAMPTZ '2024-05-08 21:14:00+03',
    17
)
ORDER BY created_at DESC, order_id DESC
LIMIT 5;
