-- =============================================================================
-- KATA 020 · Эталонное решение
-- =============================================================================
-- Почему так:
--   • Скалярный подзапрос выполняется один раз, а не для каждой строки
--     внешнего запроса, и возвращает ровно одно значение.
--   • Условие status = 'delivered' повторено внутри подзапроса: среднее
--     должно считаться по той же популяции, что и внешняя выборка.
--     Если бы среднее считалось по всем заказам, бизнес-смысл отчёта
--     изменился бы.
--   • AVG(numeric) возвращает numeric; округлять его для сравнения не нужно.
--   • Индекс (status, created_at) может помочь найти доставленные заказы,
--     хотя для агрегата по всей группе всё равно потребуется проход.
--   • Сортировка ASC/DESC задана явно, чтобы diff проверял осмысленный порядок.
-- =============================================================================

SELECT
    order_id,
    user_id,
    total_amount
FROM orders
WHERE status = 'delivered'
  AND total_amount > (
      SELECT avg(total_amount)
      FROM orders
      WHERE status = 'delivered'
  )
ORDER BY total_amount DESC, order_id ASC;
