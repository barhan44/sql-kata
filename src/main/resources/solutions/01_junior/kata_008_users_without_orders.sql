-- =============================================================================
-- KATA 008 · Эталонное решение
-- =============================================================================
-- Почему так:
--   • LEFT JOIN сохраняет всех пользователей, а условие
--     o.order_id IS NULL оставляет только тех, кому не нашлось пары.
--   • Это anti-join. В отличие от NOT IN, он корректно работает с NULL
--     в правой таблице: пользователи без заказов получают NULL в o.order_id.
--   • Для больших таблиц полезна пара индексов orders(user_id) и
--     users(user_id); первый уже создан в схеме.
--   • registered_at::date даёт стабильный тип date и убирает лишнее время
--     из отчёта.
-- =============================================================================

SELECT
    u.user_id,
    u.full_name,
    u.status,
    u.registered_at::date AS registered_on
FROM users u
LEFT JOIN orders o ON o.user_id = u.user_id
WHERE o.order_id IS NULL
ORDER BY u.user_id ASC;
