-- =============================================================================
-- Почему так:
--   • UNION по умолчанию выполняет UNION DISTINCT: сортирует/хэширует
--     объединение и убирает дубликаты. Именно это нужно для справочника.
--   • UNION ALL быстрее (не надо дедуплицировать), но вернул бы по строке
--     на каждый email и не решил бы задачу.
--   • split_part(email, '@', 2) возвращает text; обе половины UNION имеют
--     одинаковый тип, поэтому неявного приведения нет.
--   • ORDER BY относится ко всему результату UNION, а не к последнему SELECT.
-- =============================================================================

SELECT split_part(email, '@', 2) AS email_domain
FROM users
UNION
SELECT split_part(email, '@', 2) AS email_domain
FROM employees
ORDER BY email_domain ASC;
