-- Почему так:
--   • FULL OUTER JOIN сохраняет несопоставленные строки с обеих сторон:
--     отделы без сотрудников (Legal и др.) и сотрудника Kirill Osipov
--     без отдела.
--   • Для отдела с сотрудниками выводится строка на каждого сотрудника:
--   • NULLS LAST в сортировке держит аномалии в конце отчёта и делает
--     порядок воспроизводимым.
--   • На больших таблицах FULL OUTER JOIN дороже; здесь объёмы небольшие,
--     а задача — именно сверка двух множеств.
-- =============================================================================

SELECT
    d.department_id,
    d.name AS department_name,
    e.employee_id,
    e.full_name AS employee_name,
    e.salary
FROM departments d
FULL OUTER JOIN employees e ON e.department_id = d.department_id
ORDER BY d.department_id ASC NULLS LAST,
         e.employee_id ASC NULLS LAST;
