-- =============================================================================
-- KATA 001 · Эталонное решение
-- =============================================================================
-- Почему так:
--   • Обычный WHERE с SARGable-условиями: сравнение колонок с константами
--     позволяет PostgreSQL использовать индексы users(status) и
--     users(country, status), если это будет выгодно планировщику.
--   • timestamptz-литерал содержит смещение +03, поэтому граница периода
--     задана в московском времени, а не зависит от TimeZone текущей сессии.
--   • Явный ORDER BY с user_id в качестве tie-breaker делает результат
--     детерминированным: у разных пользователей может быть одинаковый
--     registered_at.
-- =============================================================================

SELECT
    user_id,
    full_name,
    email,
    registered_at
FROM users
WHERE status = 'active'
  AND country = 'RU'
  AND registered_at >= TIMESTAMPTZ '2022-01-01 00:00:00+03'
ORDER BY registered_at DESC, user_id ASC;
