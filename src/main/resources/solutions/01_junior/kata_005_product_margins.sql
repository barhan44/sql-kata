-- =============================================================================
-- KATA 005 · Эталонное решение
-- =============================================================================
-- Почему так:
--   • price и cost имеют тип numeric, поэтому арифметика точная: никаких
--     ошибок двоичной плавающей точки, как у float/double.
--   • COALESCE(stock, 0) превращает неизвестный остаток в ноль только для
--     расчёта стоимости склада; сама колонка stock в результат не входит.
--   • ROUND(..., 2) для денежных сумм и ROUND(..., 1) для процента задают
--     ожидаемую точность и, следовательно, тип/значение результата.
--   • Сортировка по псевдониму margin_percent допустима в PostgreSQL;
--     product_id обеспечивает стабильный порядок при равной марже.
-- =============================================================================

SELECT
    product_id,
    name,
    price,
    cost,
    round(price - cost, 2)                              AS margin_amount,
    round((price - cost) / price * 100, 1)              AS margin_percent,
    round(price * coalesce(stock, 0), 2)                AS inventory_value
FROM products
WHERE is_active = true
  AND price >= 10000
ORDER BY margin_percent DESC, product_id ASC;
