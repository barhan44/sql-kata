-- =============================================================================
-- KATA 003 · Эталонное решение
-- =============================================================================
-- Почему так:
--   • В PostgreSQL по умолчанию NULL считается «больше» любого значения:
--     при DESC он оказался бы сверху, при ASC — снизу. Явные NULLS LAST
--     задают бизнес-правило «неизвестные рейтинги/остатки в конце списка».
--   • BETWEEN включает обе границы, что соответствует условию.
--   • product_id — детерминированный tie-breaker для строк с одинаковыми
--     rating и stock.
--   • Для витрины дополнительный индекс (is_active, price) уже существует;
--     сам ORDER BY по rating/stock без индекса может потребовать сортировки,
--     но на таком объёме это дешевле, чем поддерживать ещё один индекс.
-- =============================================================================

SELECT
    product_id,
    name,
    rating,
    stock
FROM products
WHERE is_active = true
  AND price BETWEEN 3000 AND 100000
ORDER BY rating DESC NULLS LAST,
         stock ASC NULLS LAST,
         product_id ASC;
