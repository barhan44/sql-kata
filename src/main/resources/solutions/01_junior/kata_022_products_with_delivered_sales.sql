-- =============================================================================
-- KATA 022 · Эталонное решение
-- =============================================================================
-- Почему так:
--   • EXISTS проверяет только факт наличия строки и умеет останавливаться
--     на первой найденной (short-circuit). SELECT 1 подчёркивает, что данные
--     из подзапроса не используются.
--   • Коррелированное условие oi.product_id = p.product_id связывает подзапрос
--     с текущим товаром. JOIN orders нужен, чтобы проверить статус заказа.
--   • В отличие от JOIN + DISTINCT, EXISTS не размножает строки, если товар
--     встречается в нескольких доставленных заказах.
--   • Индексы order_items(product_id) и orders(order_id) (PK) ускоряют проверку.
-- =============================================================================

SELECT
    p.product_id,
    p.name,
    p.price
FROM products p
WHERE EXISTS (
    SELECT 1
    FROM order_items oi
    JOIN orders o ON o.order_id = oi.order_id
    WHERE oi.product_id = p.product_id
      AND o.status = 'delivered'
)
ORDER BY p.product_id ASC;
