-- KATA 021 · Эталонное решение
-- =============================================================================
-- Почему так:
--   • Агрегация вынесена в производную таблицу (подзапрос в FROM): сначала
--     считаем метрики по пользователю один раз, затем присоединяем справочник.
--   • Фильтр по avg_order_value применяется уже к агрегату, поэтому это
--     WHERE внешнего запроса, а не HAVING внутреннего — оба варианта
--     допустимы, но здесь проще читать слои.
--   • ROUND(AVG(...), 2) вычисляется до фильтрации. Это соответствует
--     контракту выходной колонки. Если бизнес-правило требует сравнивать
--     неокруглённое среднее, фильтр нужно перенести во внутренний запрос.
--   • orders(user_id, status) помогает агрегации, users(user_id) — соединению.
-- =============================================================================

SELECT
    s.user_id,
    u.full_name,
    s.delivered_orders,
    s.avg_order_value
FROM (
    SELECT
        user_id,
        count(*) AS delivered_orders,
        round(avg(total_amount), 2) AS avg_order_value
    FROM orders
    WHERE status = 'delivered'
    GROUP BY user_id
) s
JOIN users u ON u.user_id = s.user_id
WHERE s.avg_order_value >= 50000
ORDER BY s.avg_order_value DESC, s.user_id ASC;
