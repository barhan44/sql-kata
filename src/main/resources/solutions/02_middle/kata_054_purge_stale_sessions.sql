-- =============================================================================
-- KATA 054 · Эталонное решение
-- =============================================================================
-- Почему так:
--   • DELETE ... USING users соединяет удаляемую таблицу с целевой и
--     позволяет проверить бизнес-статус пользователя без подзапроса.
--   • Условие s.user_id = u.user_id обязательно: без него USING даст
--     декартово произведение всех сессий и всех пользователей.
--   • ended_at IS NOT NULL отделяет завершённые сессии от активных.
--     Строгое s.ended_at < cutoff не удаляет сессию ровно на границе.
--   • RETURNING возвращает только идентификаторы и времена, а CTE позволяет
--     отсортировать результат. В продакшене такие удаления выполняют батчами,
--     чтобы не держать долгую блокировку; здесь объём мал.
--   • Транзакция после проверки откатывается, поэтому тестовые данные
--     остаются на месте.
-- =============================================================================

WITH deleted AS (
    DELETE FROM user_sessions s
    USING users u
    WHERE s.user_id = u.user_id
      AND u.status IN ('inactive', 'blocked')
      AND s.ended_at IS NOT NULL
      AND s.ended_at < TIMESTAMPTZ '2024-06-01 00:00:00+03'
    RETURNING
        s.session_id,
        s.user_id,
        s.started_at,
        s.ended_at
)
SELECT
    session_id,
    user_id,
    started_at,
    ended_at
FROM deleted
ORDER BY session_id ASC;
