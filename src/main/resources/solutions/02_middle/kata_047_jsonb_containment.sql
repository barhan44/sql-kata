-- KATA 047 · Эталонное решение
-- =============================================================================
-- Почему так:
--   • `@>` проверяет containment: левый JSONB содержит указанную правую
--     структуру. Для объекта это означает, что все пары из правой части
--     присутствуют с теми же значениями; остальные ключи не важны.
--   • В отличие от цепочки условий preferences->>'theme' = ... AND
--     preferences->>'notifications' = ... , containment выражает намерение
--     одним предикатом и может использовать GIN-индекс.
--   • В схеме есть users_preferences_gin_idx ON users USING gin(preferences).
--     Для запросов только с @> GIN(jsonb_path_ops) был бы компактнее,
--     но jsonb_ops универсальнее (поддерживает и операторы существования).
--   • Индекс по status может помочь дополнительно, но планировщик сам выберет
--     bitmap index scan при достаточной селективности.
-- =============================================================================

SELECT
    user_id,
    full_name,
    email,
    preferences
FROM users
WHERE status = 'active'
  AND preferences @> '{"theme":"dark","notifications":true}'::jsonb
ORDER BY user_id ASC;
