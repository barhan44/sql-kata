-- =============================================================================
-- KATA 046 · Эталонное решение
-- =============================================================================
-- Почему так:
--   • payload -> 'attributes' возвращает JSONB-объект целиком, не превращая
--     его в строку. Это удобно для передачи вложенной структуры в API.
--   • #>> с массивом пути возвращает text по вложенному пути и безопасно даёт
--     NULL, если ключа нет.
--   • attempt нельзя кастовать вслепую: payload приходит из внешней системы.
--     Регулярное выражение ^[0-9]+$ проверяет, что значение действительно
--     неотрицательное целое, и только затем выполняется ::integer.
--   • Оператор `?` проверяет наличие ключа attributes на верхнем уровне
--     и не разворачивает JSON.
--   • В продакшене для частого поиска по вложенным ключам стоит рассмотреть
--     GIN(jsonb_path_ops) и запросы @> вместо регулярных выражений.
-- =============================================================================

SELECT
    log_id,
    action,
    payload -> 'attributes' AS attributes,
    payload #>> '{attributes,gateway}' AS gateway,
    CASE
        WHEN payload #>> '{attributes,attempt}' ~ '^[0-9]+$'
        THEN (payload #>> '{attributes,attempt}')::integer
    END AS attempt,
    payload #>> '{error,code}' AS error_code
FROM audit_logs
WHERE payload ? 'attributes'
ORDER BY log_id ASC;
