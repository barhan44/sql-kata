-- KATA 105 · Эталонное решение
-- =============================================================================
-- План и блокировки:
--   EXPLAIN (без ANALYZE) покажет CTE с Limit/LockRows над task_queue и
--   внешний Update. Ключевой механизм — не форма плана, а SKIP LOCKED:
--   первая транзакция блокирует выбранные строки, вторая пропускает их и
--   читает следующие. Без SKIP LOCKED второй UPDATE ждёт row lock и
--   завершается timeout.
--
-- Почему так:
--   • CTE сначала выбирает 10 NEW-задач с FOR UPDATE SKIP LOCKED. Другой
--     воркер, который зайдёт одновременно, увидит уже заблокированные строки
--     и пропустит их вместо ожидания.
--   • UPDATE ... FROM меняет статус только захваченных строк и возвращает их.
--     SELECT и UPDATE — одна команда, поэтому между ними нельзя вклиниться.
--   • ORDER BY task_id задаёт порядок обхода и делает захват предсказуемым.
--   • SKIP LOCKED — инструмент для очередей, где задачи независимы. Для
--     финансовых переводов он опасен: пропущенная заблокированная строка
--     может означать нарушение порядка обработки.
--   • Транзакция должна оставаться открытой до завершения работы воркера:
--     после COMMIT/ROLLBACK блокировки снимаются, и задача снова может быть
--     видна (в нашем тесте статус откатывается, это ожидаемо).
-- =============================================================================

WITH claimed AS (
    SELECT
        q.task_id
    FROM task_queue q
    WHERE q.status = 'NEW'
    ORDER BY q.task_id ASC
    LIMIT 10
    FOR UPDATE SKIP LOCKED
)
UPDATE task_queue q
SET status = 'PROCESSING'
FROM claimed c
WHERE q.task_id = c.task_id
RETURNING
    q.task_id,
    q.status;
