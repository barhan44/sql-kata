-- План и блокировки:
--   EXPLAIN для этого запроса покажет CTE с Limit/LockRows над
--   events_big_created_at_idx и Delete по event_id. В индексе отбирается
--   ровно 500 старых TID; SKIP LOCKED позволяет параллельным purger'ам не
--   стоять в ожидании. Короткая транзакция сокращает время удержания
--   блокировок и размер WAL; ROLLBACK теста возвращает все строки.
--
-- Почему так:
--   • CTE выбирает только 500 TID/ID старых событий. LIMIT делает одну
--     транзакцию короткой: меньше WAL, меньше удерживаемых блокировок,
--     быстрее освобождение места после VACUUM.
--   • FOR UPDATE SKIP LOCKED позволяет нескольким maintenance-воркерам
--     удалять разные пачки без ожидания друг друга. В реальном приложении
--     каждый батч коммитится отдельно.
--   • ORDER BY event_id делает выборку детерминированной; на >500 строк
--     важно понимать, какие именно ряды удалены.
--   • DELETE ... USING удаляет только выбранные ID. После проверки транзакция
--     откатывается, поэтому данные тренажёра не меняются.
--   • Возвращаем агрегат, а не 500 идентификаторов: тест проверяет число,
--     минимальный и максимальный ID, не раздувая diff.
--   • Глобальный DELETE без LIMIT на миллионах строк может держать
--     блокировки минутами, блокировать autovacuum и переполнить WAL.
-- =============================================================================

WITH batch AS (
    SELECT
        e.event_id
    FROM events_big e
    WHERE e.created_at < TIMESTAMPTZ '2025-02-01 00:00:00+03'
    ORDER BY e.event_id ASC
    LIMIT 500
    FOR UPDATE SKIP LOCKED
),
deleted AS (
    DELETE FROM events_big e
    USING batch b
    WHERE e.event_id = b.event_id
    RETURNING e.event_id
)
SELECT
    count(*) AS deleted_count,
    min(event_id) AS min_event_id,
    max(event_id) AS max_event_id
FROM deleted;
