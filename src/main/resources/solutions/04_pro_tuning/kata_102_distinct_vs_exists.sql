-- =============================================================================
-- KATA 102 · Эталонное решение
-- =============================================================================
-- EXPLAIN-анализ:
--   Index Only Scan (или Bitmap Index Scan) по
--   events_big_event_type_user_idx находит ~200 PAYMENT-событий,
--   HashAggregate сводит их к уникальным user_id, затем Hash Join с users.
--   Seq Scan на events_big отсутствует, DISTINCT и сортировка дубликатов
--   больше не нужны.
--
-- Почему так:
--   • EXISTS — semi-join: для каждого пользователя достаточно найти одну
--     PAYMENT-строку. После первого совпадения сканирование может
--     остановиться, а строки не размножаются.
--   • DISTINCT после JOIN решает симптом (дубликаты), а не причину —
--     избыточное соединение. Он также требует сортировки/хеширования.
--   • Составной индекс events_big(event_type, user_id) позволяет найти
--     пользователей по редкому event_type и сразу проверить user_id.
--     Без индекса EXISTS всё ещё корректен, но может превратиться в Seq Scan.
--   • Коррелированный EXISTS семантически безопаснее, чем IN при возможных
--     NULL в подзапросе: NULL не ломает фильтр.
--   • Для маленькой users и большой events_big PostgreSQL может выбрать
--     semi-join с хешированием; логика остаётся той же — без DISTINCT.
-- =============================================================================

SELECT
    u.user_id,
    u.full_name,
    u.email
FROM users u
WHERE EXISTS (
    SELECT 1
    FROM events_big e
    WHERE e.user_id = u.user_id
      AND e.event_type = 'PAYMENT'
)
ORDER BY u.user_id ASC;
