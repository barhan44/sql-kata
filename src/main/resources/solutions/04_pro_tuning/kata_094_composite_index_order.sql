-- =============================================================================
-- EXPLAIN (ANALYZE): Index Scan using events_big_status_created_idx
--   -> Incremental Sort (created_at, event_id) -> Limit 100.
-- Seq Scan по events_big отсутствует.
--
-- Почему так:
--   • В B-Tree индексе (status, created_at) сначала отсортирован status,
--     затем created_at. Равенство status = 'PAID' фиксирует одну область
--     индекса, и внутри неё created_at уже упорядочен. Именно поэтому
--     equality-колонка должна идти первой, range-колонка — второй.
--   • Текстовый порядок предикатов в SQL не важен: планировщик нормализует
--     WHERE. Важна физическая структура индекса.
--   • Полуоткрытый диапазон [1 мая, 1 июня) остаётся SARGable и не теряет
--     последний день месяца.
--   • По индексу прочитано чуть больше 100 строк, чтобы учесть tie-breaker
--     event_id; Incremental Sort сортирует только группы с одинаковым
--     created_at, а не весь результат.
--   • LIMIT позволяет остановить чтение индекса после заполнения 100 строк.
--     Seq Scan + полная сортировка здесь был бы заметно дороже.
-- =============================================================================

SELECT
    event_id,
    created_at,
    amount
FROM events_big
WHERE status = 'PAID'
  AND created_at >= TIMESTAMPTZ '2025-05-01 00:00:00+03'
  AND created_at <  TIMESTAMPTZ '2025-06-01 00:00:00+03'
ORDER BY created_at ASC, event_id ASC
LIMIT 100;
