-- KATA 093 · Эталонное решение
-- =============================================================================
-- EXPLAIN (ANALYZE): Bitmap Index Scan on events_big_amount_idx
--   -> Bitmap Heap Scan (20 rows) -> Sort by event_id.
-- Seq Scan по events_big отсутствует.
--
-- Почему так:
--   • Неравенство amount * 1.2 > 599000 эквивалентно amount > 599000 / 1.2
--     при положительном множителе. Правая часть — константа, вычисляемая
--     один раз, а слева остаётся «голая» индексируемая колонка.
--   • PostgreSQL хранит numeric точно; явное деление numeric на numeric даёт
--     numeric без неожиданного float-приведения. В плохом варианте
--     арифметическое выражение над amount запрещало поиск по индексу.
--   • Порог 599000/1.2 ≈ 499166.67 оставляет 20 строк из 20 000; селективность
--     отличная, поэтому Bitmap Index Scan дешевле чтения всей таблицы.
--   • Порядок по event_id всё равно требует сортировки: индекс отсортирован
--     по amount, а не по event_id. При большом результате планировщик мог бы
--     выбрать Seq Scan + Sort, если бы это было дешевле.
-- =============================================================================

SELECT
    event_id,
    status,
    amount
FROM events_big
WHERE amount > 599000 / 1.2
ORDER BY event_id ASC;
