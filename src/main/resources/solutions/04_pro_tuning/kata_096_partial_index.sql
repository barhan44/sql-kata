-- EXPLAIN (ANALYZE): Index Scan using events_big_new_retry_partial_idx
--   Index Cond: created_at в мае 2025
--   Limit 100.
-- Seq Scan по events_big отсутствует.
--
-- Почему так:
--   • Частичный индекс содержит только status='NEW' AND retry_count<3.
--     Запрос повторяет эти условия дословно, поэтому планировщик доказывает
--     импликацию и может сканировать маленький partial index.
--   • DATE(created_at) в плохом варианте ломал и SARGable-диапазон, и
--     возможность index scan. Использован полуоткрытый интервал.
--   • Индекс отсортирован по (created_at, event_id), поэтому первые 100 строк
--     читаются в нужном порядке без отдельной сортировки.
--   • retry_count <= 2 логически эквивалентно < 3 для целых, но для надёжного
--     сопоставления с предикатом индекса условие записано как < 3.
--   • Partial index меньше и дешевле в обслуживании: события других статусов
--     и с retry_count >= 3 в него не попадают.
-- =============================================================================

SELECT
    event_id,
    created_at,
    retry_count
FROM events_big
WHERE status = 'NEW'
  AND retry_count < 3
  AND created_at >= TIMESTAMPTZ '2025-05-01 00:00:00+03'
  AND created_at <  TIMESTAMPTZ '2025-06-01 00:00:00+03'
ORDER BY created_at ASC, event_id ASC
LIMIT 100;
