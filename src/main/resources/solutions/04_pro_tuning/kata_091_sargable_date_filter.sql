-- =============================================================================
-- KATA 091 · Эталонное решение
-- =============================================================================
-- EXPLAIN (ANALYZE): Bitmap Index Scan on events_big_created_at_idx
--   -> Bitmap Heap Scan on events_big (55 rows) -> Sort by event_id.
-- Seq Scan по events_big отсутствует.
--
-- Почему так:
--   • Полуоткрытый интервал сохраняет SARGable-предикат: индекс сравнивает
--     created_at напрямую. DATE(created_at) из плохого запроса требовал
--     вычисления функции для каждой строки и исключал индекс.
--   • [начало, следующий_день) не теряет события с дробными секундами
--     23:59:59.xxx, как это может случиться с BETWEEN ... AND '23:59:59'.
--   • Явный timestamptz с +03 фиксирует бизнес-зону независимо от TimeZone
--     сессии.
--   • Bitmap Heap Scan выбран планировщиком из-за компактного диапазона:
--     сначала индекс быстро находит 55 TID, затем читает нужные heap-блоки.
--   • Для очень широкого диапазона Seq Scan может быть дешевле — SARGable
--     предикат лишь делает индексный путь возможным, выбор остаётся за
--     стоимостной моделью.
-- =============================================================================

SELECT
    event_id,
    status,
    amount,
    created_at
FROM events_big
WHERE created_at >= TIMESTAMPTZ '2025-05-10 00:00:00+03'
  AND created_at <  TIMESTAMPTZ '2025-05-11 00:00:00+03'
ORDER BY event_id ASC;
