-- EXPLAIN (ANALYZE): Result -> InitPlan -> Index Only Scan using
--   events_big_user_status_idx (user_id = 5 AND status = 'FAILED').
--   Seq Scan по events_big отсутствует.
--
-- Почему так:
--   • EXISTS — semi-join: PostgreSQL может остановиться на первой подходящей
--     строке и вернуть TRUE; считать весь миллион FAILED-строк не нужно.
--   • COUNT(*) > 0 сначала агрегирует все совпадения и только потом
--     сравнивает результат с нулём.
--   • Составной индекс (user_id, status) поддерживает оба равенства. Так как
--     в индексе нет других колонок, PostgreSQL может обойтись Index Only Scan
--     (при актуальной visibility map — Heap Fetches 0).
--   • SELECT 1 в подзапросе подчёркивает, что значения не нужны; это не
--     влияет на план, но делает намерение явным.
--   • EXISTS не ломается на NULL и семантически безопаснее, чем
--     COUNT(*) = 0 / NOT IN.
-- =============================================================================

SELECT EXISTS (
    SELECT 1
    FROM events_big e
    WHERE e.user_id = 5
      AND e.status = 'FAILED'
) AS has_failed_events;
