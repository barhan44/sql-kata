-- =============================================================================
-- KATA 106 · Эталонное решение
-- =============================================================================
-- План и блокировки:
--   EXPLAIN для INSERT покажет Insert on webhook_events и Conflict
--   Resolution: NOTHING с проверкой по уникальному индексу первичного ключа.
--   При существующем event_id PostgreSQL не добавляет строку в heap и не
--   порождает side effect; возвращается 0 строк. Конкурентные вставки того
--   же ключа сериализуются на unique index, а не проходят check-then-act.
--
-- Почему так:
--   • INSERT ... ON CONFLICT (event_id) DO NOTHING — одна атомарная команда.
--     Проверка уникальности и решение «вставить/пропустить» происходят внутри
--     одной операции, без окна гонки между SELECT и INSERT.
--   • PRIMARY KEY/UNIQUE по event_id — единственный источник истины для
--     идемпотентности. Суррогатный ID не защищал бы от повторной доставки
--     того же события.
--   • RETURNING определён, но при конфликте новых строк нет, поэтому
--     результат — 0 строк. Это корректный no-op; вызывающий код может
--     повторить тот же запрос без риска дублирования.
--   • DO UPDATE здесь не нужен: он заменил бы исходные данные и усложнил
--     аудит. Если нужно обновлять время последней доставки, выбирайте
--     DO UPDATE осознанно.
--   • В реальной системе событие инициирует side effect (публикацию в
--     очередь) в той же транзакции через transactional outbox.
-- =============================================================================

INSERT INTO webhook_events (
    event_id,
    event_type,
    payload,
    received_at
)
VALUES (
    'evt-existing-001',
    'PAYMENT_SUCCEEDED',
    '{"amount": 100}'::jsonb,
    TIMESTAMPTZ '2025-06-15 12:00:00+03'
)
ON CONFLICT (event_id) DO NOTHING
RETURNING
    event_id,
    event_type,
    payload,
    received_at;
