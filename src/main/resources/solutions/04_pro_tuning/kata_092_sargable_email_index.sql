-- EXPLAIN (ANALYZE): Index Scan using events_big_lower_email_idx (1 row).
-- Seq Scan по events_big отсутствует.
--
-- Почему так:
--   • Индекс создан по выражению lower(email), поэтому предикат запроса
--     должен использовать точно то же выражение. PostgreSQL сопоставляет
--     lower(email) = lower('...') с индексным выражением и выполняет Search.
--   • Константа нормализуется один раз; в индекс уходит уже 'target.user@...'.
--   • Ведущий '%' в LIKE не позволил бы B-Tree найти диапазон: B-Tree
--     сортирует строки слева, а шаблон с произвольным префиксом требует
--     полного сканирования.
--   • Для регистрозависимого префиксного поиска (email LIKE 'Target.%')
--     подходит events_big_email_pattern_idx с text_pattern_ops: он сравнивает
--     байты и не зависит от collation для поиска диапазона. Для
--     регистронезависимого точного поиска — этот lower-индекс.
--   • text_pattern_ops полезен именно для LIKE 'prefix%', а не для
--     '%substring%': последний невозможно ускорить обычным B-Tree.
-- =============================================================================

SELECT
    event_id,
    email
FROM events_big
WHERE lower(email) = lower('Target.User@Example.com')
ORDER BY event_id ASC;
