-- План и блокировки:
--   EXPLAIN (без ANALYZE) показывает Update on ledger_accounts через
--   первичный ключ account_id с Filter по version и balance. Обновление
--   одной строки удерживает row lock до COMMIT/ROLLBACK; конкурентный UPDATE
--   перечитает актуальную version. Ожидаемый результат — 0 строк: balance
--   недостаточен, поэтому RETURNING ничего не вернёт и овердрафта не будет.
--
-- Почему так:
--   • Один UPDATE атомарно проверяет и изменяет строку. Нет окна между
--     SELECT и UPDATE, в которое параллельная транзакция может изменить
--     balance/version.
--   • version = 1 — оптимистичная блокировка: если другой процесс уже
--     обновил счёт, версия изменится, и наш UPDATE не затронет строку.
--   • balance >= 1500.00 — инвариант денег. Даже при совпавшей версии
--     списание не произойдёт, если денег недостаточно; строка не станет
--     отрицательной.
--   • WHERE-условия используют один и тот же снимок строки. PostgreSQL
--     сериализует конкурентные UPDATE на строке: второй ждёт фиксации
--     первого и перечитывает version, поэтому условие проверяется корректно.
--   • Здесь ожидается 0 строк: баланс 1000 < 1500. Вызывающий код должен
--     трактовать это как business error и повторить операцию только при
--     конфликте версии/изменении суммы.
--   • При частых конфликтах оптимистичная блокировка может проигрывать
--     SELECT ... FOR UPDATE; выбор зависит от contention и логики ретраев.
-- =============================================================================

UPDATE ledger_accounts
SET balance = balance - 1500.00,
    version = version + 1
WHERE account_id = 1
  AND version = 1
  AND balance >= 1500.00
RETURNING
    account_id,
    user_id,
    balance,
    version;
