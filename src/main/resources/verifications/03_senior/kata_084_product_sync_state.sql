-- =============================================================================
-- KATA 084 · Проверка состояния после MERGE
-- =============================================================================
-- Возвращает все товары в стабильном порядке. После MERGE должны исчезнуть
-- LPT-ZN14 и CAM-WEB4K, обновиться PHN-IP15/FRN-DSK1, появиться ACC-DOCK1
-- и HOM-NSM1. Проверочный SELECT выполняется в той же транзакции, что и MERGE,
-- затем транзакция откатывается.
-- =============================================================================

SELECT
    product_id,
    sku,
    name,
    category_id,
    price,
    cost,
    stock,
    rating,
    tags,
    attributes,
    is_active,
    created_at
FROM products
ORDER BY product_id ASC;
