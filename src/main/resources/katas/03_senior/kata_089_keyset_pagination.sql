-- Бизнес-контекст
--   API отдаёт последние заказы постранично. OFFSET со временем деградирует:
--   СУБД всё равно читает и пропускает все предыдущие строки. Keyset-пагинация
--   использует последний ключ предыдущей страницы и индекс.
--
-- Таблица
--   orders(order_id, user_id, created_at, total_amount, ...)
--
-- Параметры страницы
--   курсор: created_at = 2024-05-08 21:14:00+03, order_id = 17;
--   размер страницы: 5;
--   порядок: created_at DESC, order_id DESC.
--
-- Требования
--   1. Используй row-value сравнение:
--        (created_at, order_id) < (курсор_created_at, курсор_order_id).
--   2. Верни следующую страницу: ровно четыре колонки:
--        order_id      integer
--        user_id       integer
--        created_at    timestamptz
--        total_amount  numeric(12,2)
--   3. Сортировка: created_at DESC, order_id DESC.
--   4. LIMIT 5.
--   5. В комментариях объясни, почему row-value comparison корректнее, чем
--      отдельное `created_at < cursor` (потеря заказов с тем же временем),
--      и почему OFFSET деградирует на глубоких страницах.
--
-- Проверка
--   Сравниваются имена/типы колонок, значения и порядок строк.
