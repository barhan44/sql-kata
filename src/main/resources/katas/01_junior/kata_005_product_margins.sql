-- Бизнес-контекст
--   Категорийный менеджер хочет видеть прибыль по активным товарам дороже
--   10 000 рублей. Остаток может быть неизвестен (NULL): для расчёта стоимости
--   склада его нужно считать нулевым, иначе всё произведение станет NULL.
--
-- Таблица
--   products(product_id, name, price, cost, stock, is_active, ...)
--
-- Требования
--   1. Отбери is_active = true AND price >= 10000.
--   2. Верни ровно семь колонок в указанном порядке:
--        product_id       integer
--        name             text
--        price            numeric(10,2)
--        cost             numeric(10,2)
--        margin_amount    numeric — round(price - cost, 2)
--        margin_percent   numeric — round((price - cost) / price * 100, 1)
--        inventory_value  numeric — round(price * COALESCE(stock, 0), 2)
--   3. Сортировка: margin_percent DESC, затем product_id ASC.
--   4. LIMIT не использовать.
--
-- Обрати внимание
--   price заведомо больше нуля (CHECK в схеме), поэтому деление на ноль здесь
--   невозможно. NULL в stock не должен превращать inventory_value в NULL.
--
-- Проверка
--   Сравниваются имена колонок, их типы, значения и порядок строк.
-- =============================================================================

SELECT 1 WHERE FALSE;
