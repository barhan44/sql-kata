--        user_id           integer
--        full_name         text
--        phone_display     text  — COALESCE(phone, 'phone not provided')
--        loyalty_display   text  — COALESCE(loyalty_tier, 'no tier')
--   4. Сортировка: user_id ASC. LIMIT не использовать.
--
-- Важно
--   Значения-заглушки должны быть строго такими:
--     'phone not provided' для отсутствующего телефона;
--     'no tier' для отсутствующего уровня лояльности.
--
-- Проверка
--   Сравниваются имена колонок, их типы, значения и порядок строк.
