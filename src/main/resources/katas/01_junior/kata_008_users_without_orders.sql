-- Бизнес-контекст
--   CRM-команда ищет «спящих» зарегистрированных пользователей, которые ещё
--   ничего не купили. Это классическая задача поиска отсутствующих связей:
--   LEFT JOIN + проверка NULL на стороне правой таблицы.
--
-- Таблицы
--   users(user_id, full_name, status, registered_at, ...)
--   orders(order_id, user_id, ...)
--
-- Требования
--   1. Верни всех пользователей, у которых нет ни одного заказа, независимо
--      от их статуса (active/inactive/blocked).
--   2. Верни ровно четыре колонки в указанном порядке:
--        user_id        integer
--        full_name      text
--        status         text
--        registered_on  date — registered_at, приведённый к дате
--   3. Сортировка: user_id ASC.
--   4. Используй именно LEFT JOIN и условие orders.order_id IS NULL
--      (anti-join). NOT IN здесь опасен, если бы user_id мог быть NULL.
--
-- Проверка
--   Сравниваются имена колонок, их типы, значения и порядок строк.
-- =============================================================================

