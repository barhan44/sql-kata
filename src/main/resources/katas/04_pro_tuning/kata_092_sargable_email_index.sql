--   1. Выполни ТОЧНЫЙ поиск без учёта регистра:
--        lower(email) = lower('Target.User@Example.com')
--      (никаких ведущих '%').
--   2. Верни ровно две колонки:
--        event_id  bigint
--        email     text
--   3. Сортировка: event_id ASC.
--   4. В комментариях к решению объясни, когда для префиксного поиска нужен
--      text_pattern_ops, а когда — обычное равенство по lower(email).
--
-- Проверка
--   Сравниваются имена/типы колонок, значения и порядок строк.
