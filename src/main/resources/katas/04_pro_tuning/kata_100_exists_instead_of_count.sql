-- =============================================================================
-- KATA 100 · Pro · EXISTS вместо COUNT(*) > 0
-- =============================================================================
-- Бизнес-контекст
--   Нужно быстро проверить, есть ли у пользователя 5 хотя бы одно FAILED-
--   событие. Ответ — boolean, а не количество.
--
-- Таблица
--   events_big(event_id, user_id, status, ...)
--   Индекс: events_big_user_status_idx ON (user_id, status).
--
-- Плохой исходный запрос
--   SELECT count(*) > 0 AS has_failed_events
--   FROM events_big
--   WHERE user_id = 5 AND status = 'FAILED';
--   Даже при наличии индекса COUNT(*) склонен посчитать все подходящие
--   строки, хотя для boolean достаточно первой. На больших объёмах это
--   лишняя работа, особенно при частых проверках.
--
-- Требования
--   1. Используй EXISTS (SELECT 1 FROM events_big WHERE ...).
--   2. Верни ровно одну колонку:
--        has_failed_events boolean
--   3. Результат — одна строка.
--   4. В комментариях объясни, почему EXISTS умеет остановиться на первой
--      найденной строке и почему это особенно важно для полу-join проверок.
--
-- Проверка
--   Сравниваются имена/типы колонок, значения и порядок строк.
--   Тест дополнительно проверяет, что индекс по (user_id, status) используется.
-- =============================================================================

SELECT 1 WHERE FALSE;
