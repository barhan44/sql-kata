-- Бизнес-контекст
--   Финансовый монитор хочет распределение статусов событий типа PAYMENT
--   в валюте USD. metadata — JSONB, для неё есть GIN-индекс.
--
-- Таблица
--   events_big(event_id, status, metadata jsonb, ...)
--   Индекс: events_big_metadata_gin_idx ON events_big USING gin(metadata).
--
-- Плохой исходный запрос
--   SELECT status, count(*)
--   FROM events_big
--   WHERE metadata->>'type' = 'PAYMENT'
--     AND metadata->>'currency' = 'USD'
--   GROUP BY status
--   ORDER BY status;
--   Причина: оператор ->> извлекает текст, и GIN-индекс по JSONB не может
--   напрямую обслужить два значения в разных ключах; PostgreSQL вынужден
--   проверять выражение для каждой строки.
--
-- Требования
--   1. Замени фильтр на containment:
--        metadata @> '{"type":"PAYMENT","currency":"USD"}'::jsonb
--   2. Верни ровно две колонки:
--        status        text
--        events_count  bigint
--   3. Сортировка: status ASC.
--   4. Объясни разницу между @> и ->> для планировщика и какую роль играет
--      GIN(jsonb_ops).
--
-- Проверка
--   Сравниваются имена/типы колонок, значения и порядок строк.
--   Тест проверяет events_big_metadata_gin_idx и отсутствие Seq Scan.
