-- =============================================================================
-- KATA 104 · Pro · NOT IN с NULL → Anti-Join
-- =============================================================================
-- Бизнес-контекст
--   Нужно найти пользователей, которые никогда не были актором в audit_logs.
--   Поле actor_user_id допускает NULL для системных событий, поэтому
--   NOT IN по нему неожиданно возвращает пустой результат.
--
-- Таблицы
--   users(user_id, full_name, email, ...)
--   audit_logs(log_id, actor_user_id, ...)
--
-- Плохой исходный запрос
--   SELECT u.user_id, u.full_name, u.email
--   FROM users u
--   WHERE u.user_id NOT IN (SELECT actor_user_id FROM audit_logs)
--   ORDER BY u.user_id;
--   Причина: в подзапросе есть NULL. Сравнение NOT IN с NULL даёт UNKNOWN,
--   и итоговый фильтр отбрасывает все строки. Кроме того, NOT IN требует
--   полного списка и не даёт планировщику semi/anti-join с ранней остановкой.
--
-- Требования
--   1. Используй NOT EXISTS (anti-join), не меняя семантику «никогда не был
--      актором».
--   2. Верни ровно три колонки:
--        user_id    integer
--        full_name  text
--        email      text
--   3. Сортировка: user_id ASC.
--   4. Объясни трёхзначную логику и почему LEFT JOIN ... IS NULL или
--      NOT EXISTS безопаснее.
--
-- Проверка
--   Сравниваются имена/типы колонок, значения и порядок строк.
-- =============================================================================

SELECT 1 WHERE FALSE;
