--   Нужно найти события, в описании которых встречается слово failed,
--   и сгруппировать их по статусу. Предвычисленный tsvector позволяет
--   использовать GIN-индекс вместо сканирования ILIKE.
--
-- Таблица
--   events_big(status, description, search_vector tsvector, ...)
--   Индекс: events_big_search_gin_idx ON events_big USING gin(search_vector).
--
-- Плохой исходный запрос
--   SELECT status, count(*)
--   FROM events_big
--   WHERE description ILIKE '%failed%'
--   GROUP BY status
--   ORDER BY status;
--   Причина: ILIKE с ведущим '%' не может использовать обычный B-Tree,
--   а полнотекстового индекса для description нет. PostgreSQL читает все
--   строки и сопоставляет подстроку.
--
-- Требования
--   1. Используй search_vector @@ to_tsquery('simple','failed').
--   2. Верни ровно две колонки:
--        status        text
--        events_count  bigint
--   3. Сортировка: status ASC.
--   4. Объясни, почему конфигурация 'simple' делает результат
--      детерминированным и какие ограничения у stemming/словарей.
--
-- Проверка
--   Сравниваются имена/типы колонок, значения и порядок строк.
--   Тест проверяет events_big_search_gin_idx и отсутствие Seq Scan.
