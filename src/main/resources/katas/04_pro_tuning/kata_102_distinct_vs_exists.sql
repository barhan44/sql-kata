--   Нужен список клиентов, у которых есть хотя бы одно событие типа PAYMENT.
--   В events_big у клиента много строк, поэтому прямой JOIN размножает
--   пользователей, а DISTINCT затем тратит время на дедупликацию.
--
-- Таблицы
--   users(user_id, full_name, email, ...)
--   events_big(event_id, user_id, event_type, ...)
--
-- Плохой исходный запрос
--   SELECT DISTINCT u.user_id, u.full_name, u.email
--   FROM users u
--   JOIN events_big e ON e.user_id = u.user_id
--   WHERE e.event_type = 'PAYMENT'
--   ORDER BY u.user_id;
--   Причина: JOIN создаёт по строке на каждое PAYMENT-событие, затем DISTINCT
--   сортирует/хеширует результат. Нам нужен только факт существования.
--
-- Требования
--   1. Перепиши через коррелированный EXISTS (semi-join).
--   2. Верни ровно три колонки:
--        user_id    integer
--        full_name  text
--        email      text
--   3. Сортировка: user_id ASC.
--   4. В комментариях объясни, почему semi-join останавливается на первом
--      совпадении и почему DISTINCT является запахом размножения строк.
--
-- Проверка
--   Сравниваются имена/типы колонок, значения и порядок строк.
--   Тест проверяет использование events_big_event_type_user_idx.
