-- Бизнес-контекст
--   Два процесса могут одновременно списать деньги с одного счёта. Нужна
--   атомарная проверка версии и достаточности баланса; при неуспехе UPDATE
--   не должен изменить ни одной строки.
--
-- Таблица
--   ledger_accounts(account_id, user_id, balance, version)
--   account_id = 1: balance = 1000.00, version = 1.
--
-- Плохой исходный подход
--   SELECT balance, version FROM ledger_accounts WHERE account_id = 1;
--   -- проверка в приложении...
--   UPDATE ledger_accounts SET balance = 1500.00 - 1500.00, version = version + 1
--   WHERE account_id = 1;
--   Причина: SELECT и UPDATE не атомарны; параллельный процесс может
--   изменить версию/баланс между ними. Условие баланса также должно быть
--   частью UPDATE, иначе можно уйти в овердрафт.
--
-- Требования
--   1. Выполни ОДИН UPDATE:
--        SET balance = balance - 1500.00,
--            version = version + 1
--      WHERE account_id = 1
--        AND version = 1
--        AND balance >= 1500.00
--   2. Верни через RETURNING ровно четыре колонки:
--        account_id integer
--        user_id    integer
--        balance    numeric(14,2)
--        version    bigint
--   3. Баланс счёта 1000.00 недостаточен для списания 1500.00, поэтому
--      ожидается 0 строк: операция должна быть отклонена без овердрафта.
--   4. Объясни, как условие version решает lost update, а balance >= —
--      защищает инвариант денег.
--
-- Проверка
--   Сравниваются имена/типы колонок, значения и порядок строк.
-- =============================================================================

