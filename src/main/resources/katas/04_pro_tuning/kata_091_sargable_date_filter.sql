--   Нужен список всех событий за 10 мая 2025 года. В продакшене таблица
--   events_big содержит десятки миллионов строк; запрос должен использовать
--   B-Tree-индекс по created_at.
--
-- Таблица
--   events_big(event_id, status, amount, created_at, ...) — 20 000 строк.
--
-- Плохой исходный запрос
--   SELECT event_id, status, amount, created_at
--   FROM events_big
--   WHERE DATE(created_at) = DATE '2025-05-10'
--   ORDER BY event_id;
--   Причина: функция DATE(created_at) применяется к каждой строке. Индекс
--   events_big_created_at_idx хранит created_at, а не DATE(created_at),
--   поэтому PostgreSQL не может использовать его как SARGable-предикат и
--   читает всю таблицу.
--
-- Требования
--   1. Перепиши фильтр как полуоткрытый интервал:
--        created_at >= TIMESTAMPTZ '2025-05-10 00:00:00+03'
--        AND created_at < TIMESTAMPTZ '2025-05-11 00:00:00+03'
--   2. Верни ровно четыре колонки:
--        event_id    bigint
--        status      text
--        amount      numeric(12,2)
--        created_at  timestamptz
--   3. Сортировка: event_id ASC.
--   4. В комментариях к решению объясни, почему полуоткрытый интервал
--      безопаснее BETWEEN и как индекс events_big_created_at_idx сокращает
--      чтение.
--
-- Проверка
--   Сравниваются имена/типы колонок, значения и порядок строк.
--   Дополнительно тест проверяет, что план использует
--   events_big_created_at_idx и не содержит Seq Scan по events_big.
