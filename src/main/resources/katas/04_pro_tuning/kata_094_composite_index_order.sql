-- Бизнес-контекст
--   API отдаёт последние 100 оплаченных событий за май 2025. Нужно
--   использовать составной индекс `(status, created_at)`: сначала равенство
--   по status, затем диапазон по created_at.
--
-- Таблица
--   events_big(event_id, status, created_at, amount, ...)
--   Индекс: events_big_status_created_idx ON (status, created_at).
--
-- Плохой исходный запрос
--   SELECT event_id, created_at, amount
--   FROM events_big
--   WHERE created_at BETWEEN '2025-05-01' AND '2025-05-31'
--     AND status = 'PAID'
--   ORDER BY created_at, event_id
--   LIMIT 100;
--   Сам по себе он может быть корректен, но для составного индекса важно,
--   чтобы equality-колонка (status) была первой, а range-колонка
--   (created_at) — второй. Индекс с обратным порядком не сможет эффективно
--   отсечь диапазон по второму столбцу. Кроме того, BETWEEN по датам без
--   времени захватывает не весь последний день — используй полуоткрытый
--   интервал.
--
-- Требования
--   1. Используй предикаты:
--        status = 'PAID'
--        created_at >= TIMESTAMPTZ '2025-05-01 00:00:00+03'
--        created_at <  TIMESTAMPTZ '2025-06-01 00:00:00+03'
--   2. Верни ровно три колонки:
--        event_id    bigint
--        created_at  timestamptz
--        amount      numeric(12,2)
--   3. Сортировка: created_at ASC, event_id ASC.
--   4. LIMIT 100.
--   5. Объясни в решении, почему Equality first, Range second важен именно
--      для B-Tree, а не для текстового порядка условий в SQL.
--
-- Проверка
--   Сравниваются имена/типы колонок, значения и порядок строк.
--   Тест проверяет events_big_status_created_idx и отсутствие Seq Scan.
