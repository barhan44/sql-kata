-- KATA 099 · Pro · Оптимизация OR по разным колонкам через UNION ALL
-- =============================================================================
-- Бизнес-контекст
--   Нужны PAID-события, где user_id = 7 ИЛИ merchant_id = 7. В данных есть
--   события, подходящие под оба условия; результат не должен содержать
--   дубликатов.
--
-- Таблица
--   events_big(event_id, user_id, merchant_id, status, amount, ...)
--   Индексы: events_big_user_status_idx (user_id, status),
--            events_big_merchant_status_created_idx (merchant_id, status, created_at).
--
-- Плохой исходный запрос
--   SELECT event_id, user_id, merchant_id, status, amount
--   FROM events_big
--   WHERE (user_id = 7 OR merchant_id = 7)
--     AND status = 'PAID'
--   ORDER BY event_id;
--   Причина: OR по разным колонкам часто приводит к Seq Scan или дорогому
--   BitmapOr, а выбирать и дедуплицировать строки приходится всем операторам.
--
-- Требования
--   1. Перепиши через UNION ALL двух индексных запросов.
--   2. Вторая ветка должна исключить уже выбранные строки:
--        merchant_id = 7 AND user_id <> 7.
--      Это сохраняет дух OR и предотвращает дубликаты.
--   3. Верни ровно пять колонок:
--        event_id     bigint
--        user_id      integer
--        merchant_id  integer
--        status       text
--        amount       numeric(12,2)
--   4. Сортировка: event_id ASC.
--   5. В решении объясни, почему UNION (а не UNION ALL) добавил бы лишнюю
--      сортировку/дедупликацию и почему явное исключение эффективнее.
--
-- Проверка
--   Сравниваются имена/типы колонок, значения и порядок строк.
--   Тест проверяет использование обоих индексов и отсутствие Seq Scan.
-- =============================================================================

