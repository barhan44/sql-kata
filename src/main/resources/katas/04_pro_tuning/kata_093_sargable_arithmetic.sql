-- Бизнес-контекст
--   Финансовый монитор ищет все события с суммой, которая после начисления
--   20% превышает 599 000. Нужно сохранить ровно тот же набор строк и
--   использовать индекс по amount.
--
-- Таблица
--   events_big(event_id, status, amount, ...)
--   Индекс: events_big_amount_idx ON (amount).
--
-- Плохой исходный запрос
--   SELECT event_id, status, amount
--   FROM events_big
--   WHERE amount * 1.2 > 599000
--   ORDER BY event_id;
--   Причина: вычисление над индексируемой колонкой делает предикат
--   не-SARGable. Кроме того, смешение numeric и float-literal может добавить
--   неявное приведение. PostgreSQL вынужден читать и вычислять выражение для
--   каждой строки.
--
-- Требования
--   1. Перепиши предикат без функции над индексируемой колонкой:
--        amount > 599000 / 1.2
--      Используй numeric-арифметику и явные числовые литералы.
--   2. Верни ровно три колонки:
--        event_id  bigint
--        status    text
--        amount    numeric(12,2)
--   3. Сортировка: event_id ASC.
--   4. В комментариях к решению покажи эквивалентность преобразования и
--      объясни, почему деление констант выполняется один раз при
--      планировании/выполнении, а не для каждой строки.
--
-- Проверка
--   Сравниваются имена/типы колонок, значения и порядок строк.
--   Тест проверяет использование events_big_amount_idx и отсутствие
--   Seq Scan по events_big.
