-- Бизнес-контекст
--   Платёжный провайдер повторяет вебхук с тем же event_id. Приложение
--   сначала проверяло наличие через SELECT, затем вставляло запись — между
--   этими шагами возможна гонка, приводящая к duplicate key или двойной
--   обработке.
--
-- Таблица
--   webhook_events(event_id text PRIMARY KEY, event_type, payload jsonb,
--                  received_at)
--   Событие evt-existing-001 уже зарегистрировано.
--
-- Плохой исходный подход
--   SELECT 1 FROM webhook_events WHERE event_id = 'evt-existing-001';
--   -- если не найдено:
--   INSERT INTO webhook_events ...
--   Причина: check-then-act не атомарен. Два процесса могут одновременно
--   пройти SELECT и затем один из них упадёт на PK, либо событие будет
--   обработано дважды.
--
-- Требования
--   1. Одним INSERT ... ON CONFLICT (event_id) DO NOTHING зарегистрируй
--      событие:
--        event_id    = 'evt-existing-001'
--        event_type  = 'PAYMENT_SUCCEEDED'
--        payload     = '{"amount": 100}'
--        received_at = TIMESTAMPTZ '2025-06-15 12:00:00+03'
--   2. Верни ровно четыре колонки через RETURNING:
--        event_id     text
--        event_type   text
--        payload      jsonb
--        received_at  timestamptz
--   3. Так как event_id уже существует, ожидается 0 строк — корректный
--      идемпотентный no-op.
--   4. Не используй отдельный SELECT перед INSERT.
--
-- Проверка
--   Сравниваются имена/типы колонок, значения и порядок строк.
-- =============================================================================

SELECT 1 WHERE FALSE;
