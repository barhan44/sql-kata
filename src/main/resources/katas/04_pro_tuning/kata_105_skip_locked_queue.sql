-- KATA 105 · Pro · Атомарный захват очереди (FOR UPDATE SKIP LOCKED)
-- =============================================================================
-- Бизнес-контекст
--   Несколько воркеров одновременно забирают задачи из task_queue. Каждый
--   должен получить 10 уникальных NEW-задач, пометить их PROCESSING и не
--   ждать задачи, уже захваченные другим воркером.
--
-- Таблица
--   task_queue(task_id, task_type, status, retry_count, payload, created_at)
--   60 задач со статусом NEW.
--
-- Плохой исходный подход
--   SELECT task_id FROM task_queue WHERE status = 'NEW' LIMIT 10;
--   -- затем в приложении: UPDATE ... WHERE task_id IN (...)
--   Причина: между SELECT и UPDATE другой воркер успевает взять те же строки.
--   Без SKIP LOCKED параллельные воркеры стоят в очереди на блокировке.
--
-- Требования
--   1. Одной SQL-командой выбери 10 NEW-задач с блокировкой:
--        ORDER BY task_id LIMIT 10 FOR UPDATE SKIP LOCKED.
--   2. Через CTE выполни UPDATE ... FROM и переведи статус в 'PROCESSING'.
--   3. Верни ровно две колонки:
--        task_id  integer
--        status   text — всегда 'PROCESSING'
--   4. Транзакцию не коммить: тест сам удерживает транзакцию и откатывает её.
--   5. Тест использует два параллельных JDBC-соединения и проверяет, что
--      пачки не пересекаются и не блокируются.
--
-- Проверка
--   Специальный тест: два воркера, каждый получает batch size = 10,
--   множества task_id не пересекаются, статусы PROCESSING.
-- =============================================================================

