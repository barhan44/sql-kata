-- Бизнес-контекст
--   Нужно удалять старые события порциями по 500 строк, не блокируя таблицу
--   на минуты. Захват пачки должен пропускать строки, уже обрабатываемые
--   другими maintenance-воркерами.
--
-- Таблица
--   events_big(event_id, created_at, ...)
--   Индекс: events_big_created_at_idx.
--
-- Плохой исходный запрос
--   DELETE FROM events_big
--   WHERE created_at < TIMESTAMPTZ '2025-02-01 00:00:00+03';
--   Причина: одна огромная транзакция удерживает блокировки и раздувает WAL,
--   а при сбое откатывает всю работу. Нужны маленькие батчи с отдельными
--   коммитами в реальном приложении и SKIP LOCKED для параллельных purger'ов.
--
-- Требования
--   1. Через CTE выбери ровно 500 самых старых event_id (ORDER BY event_id)
--      с created_at < TIMESTAMPTZ '2025-02-01 00:00:00+03',
--      используя FOR UPDATE SKIP LOCKED.
--   2. Удали выбранные строки через DELETE ... USING.
--   3. Верни одну строку с тремя колонками:
--        deleted_count  bigint
--        min_event_id   bigint
--        max_event_id   bigint
--   4. В решении объясни, почему LIMIT + SKIP LOCKED + батч-коммиты
--      предпочтительнее одного DELETE на миллионы строк.
--   5. Транзакция проверяется с откатом; реальные данные не меняются.
--
-- Проверка
--   Сравниваются имена/типы колонок, значения и порядок строк.
-- =============================================================================

