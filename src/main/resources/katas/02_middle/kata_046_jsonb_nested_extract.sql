-- Бизнес-контекст
--   Аудит-события содержат вложенный JSONB. Для разбора инцидентов нужны
--   атрибуты платёжного шлюза, номер попытки и код ошибки. JSON нетипизирован,
--   поэтому перед приведением attempt к integer нужно проверить формат,
--   иначе один кривой payload уронит весь отчёт.
--
-- Таблица
--   audit_logs(log_id, action, occurred_at, success, payload, ...)
--
-- Требования
--   1. Рассматривай события, у которых в payload есть ключ attributes
--      (оператор существования `?`).
--   2. Получи:
--        - весь вложенный объект attributes через `->` (jsonb);
--        - gateway через `#>> '{attributes,gateway}'`;
--        - attempt как integer только если текстовое значение состоит из цифр;
--          иначе NULL;
--        - error_code через `#>> '{error,code}'`, может быть NULL.
--   3. Верни ровно шесть колонок в указанном порядке:
--        log_id      bigint
--        action      text
--        attributes  jsonb
--        gateway     text
--        attempt     integer
--        error_code  text
--   4. Сортировка: log_id ASC.
--
-- Подсказка
--   `->` возвращает jsonb, `->>` — text, `#>>` — text по пути массива.
--   Для проверки числа используй регулярное выражение до CAST.
--
-- Проверка
--   Сравниваются имена/типы колонок, значения и порядок строк.
