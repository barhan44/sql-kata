--        user_id    integer
--        full_name  text
--        email      text
--   4. Сортировка: user_id ASC.
--   5. Один пользователь должен встречаться один раз независимо от числа
--      купленных смартфонов.
--
-- Подсказка
--   EXCEPT работает как множество и автоматически убирает дубликаты.
--   Сравни в комментариях с NOT EXISTS и NOT IN по NULL.
--
-- Проверка
--   Сравниваются имена/типы колонок, значения и порядок строк.
