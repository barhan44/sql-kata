-- Бизнес-контекст
--   Импорт каталога получает пачку товаров и должен:
--     • обновить существующий товар по уникальному SKU;
--     • вставить новый товар, если SKU ещё нет.
--   Один INSERT ... ON CONFLICT решает обе задачи атомарно.
--
-- Таблица
--   products(product_id, sku, name, category_id, price, cost, stock, rating,
--            tags, attributes, is_active, created_at)
--   Уникальный бизнес-ключ: sku.
--
-- Входные строки
--   1) SKU 'PHN-IP15' (уже существует), product_id = 9001,
--      price = 87990.00, stock = 20, is_active = true.
--      Остальные поля для конфликтной строки можно передать исходными.
--      При конфликте по sku нужно обновить price, stock, is_active.
--   2) SKU 'MID-KBD9' (новый), product_id = 9002, name = 'Middle Mechanical
--      Keyboard', category_id = 1, price = 14900.00, cost = 9000.00,
--      stock = 6, rating = 4.7, tags = ARRAY['accessory','keyboard'],
--      attributes = {"layout":"ansi","switches":"brown"}, is_active = true,
--      created_at = DATE '2024-07-01'.
--
-- Почему явные product_id
--   Верификатор выполняет кандидата и эталон в разных транзакциях с ROLLBACK.
--   PostgreSQL-последовательности НЕ откатываются, поэтому auto-generated id
--   у двух запусков отличались бы. Для детерминированной проверки передай
--   существующий product_id в поле 9001, а для нового — 9002. Конфликт по
--   первичному ключу не возникнет: 9001 и 9002 свободны.
--
-- Требования
--   1. Используй INSERT ... ON CONFLICT (sku) DO UPDATE.
--   2. В DO UPDATE обратись к псевдотаблице EXCLUDED; обнови price, stock,
--      is_active. Не меняй product_id существующей строки.
--   3. Верни ВСЕ колонки products через RETURNING *.
--   4. Оберни оператор в CTE и отсортируй итог по sku ASC, чтобы порядок двух
--      строк был детерминирован.
--   5. Одна SQL-команда; изменения откатятся после проверки.
--
-- Проверка
--   Сравниваются имена/типы колонок, значения и порядок строк. Должны
--   вернуться две строки: обновлённый старый товар и новый MID-KBD9.
-- =============================================================================

